"""Write a generated block: block JSON, structural Verilog, behavioural RTL and a testbench.

The block JSON (instances, shapes, vias, pins, pin positions, rows, boundary, layer
map) is self-contained: the GDS back end needs only it and the std-cell GDS.
"""
import json
import os


def block_json(blk):
    t = blk.t
    blk.fill_notches()
    return {
        "top": blk.name,
        "tech": t.name,
        "row_h": t.row_h,
        "insts": blk.insts,
        "shapes": blk.shapes,
        "vias": blk.vias,
        "via_size": {"via1": t.v1.size, "via2": t.v2.size},
        "pins": blk.pins,
        "boundary": blk.boundary,
        "rows": sorted([yb, o] for yb, o in blk.rows.items()),
        "pinpos": [[i, p, x, y, net] for net, ips in blk.conn.items() for (i, p) in ips
                   for (x, y) in [blk.pinpos[(i, p)]]],
        "cells": {c: {"w": t.macros[c]["w"]} for c in sorted(set(i[1] for i in blk.insts))},
        "rails": {t.vdd: t.rail[t.vdd][0], t.vss: t.rail[t.vss][0]},
        "layers": {
            "m1": list(t.m1.gds), "v1": list(t.v1.gds), "m2": list(t.m2.gds),
            "v2": list(t.v2.gds), "m3": list(t.m3.gds),
            "m2_text": list(t.m2.text) if t.m2.text else None,
            "boundary": list(t.boundary) if t.boundary else None,
        },
        "zoom": getattr(blk, "zoom", {}),
        "meta": blk.meta,
    }


def _port_decl(ports):
    return "\n".join("  %s %s%s;" % (d, "[%d:0] " % (w - 1) if w > 1 else "", name) for name, d, w in ports)


def write_verilog(blk, path):
    t = blk.t
    port_nets = set()
    for name, _, w in blk.ports:
        port_nets |= {name} if w == 1 else {"%s[%d]" % (name, i) for i in range(w)}
    wires = sorted(n for n in blk.conn if n not in port_nets and n not in (t.vdd, t.vss))
    pins_of = {}
    for net, ips in blk.conn.items():
        for i, p in ips:
            pins_of.setdefault(i, []).append((p, net))
    with open(path, "w") as f:
        f.write("// Generated by Digital_Layout_Auto (%s, tech %s): layout netlist\n"
                % (blk.meta.get("block", "block"), t.name))
        f.write("module %s (%s);\n" % (blk.name, ", ".join(p[0] for p in blk.ports)))
        f.write(_port_decl(blk.ports) + "\n")
        for n in wires:
            f.write("  wire %s;\n" % n)
        for name, cell, x, yb, o in blk.insts:
            if name not in pins_of:
                continue
            f.write("  %s %s (%s);\n" % (cell, name, ", ".join(".%s(%s)" % pn for pn in sorted(pins_of[name]))))
        f.write("endmodule\n")


def write_decoder_rtl(blk, path):
    n, en = blk.meta["n_bits"], blk.meta["enable"]
    N = 1 << n
    with open(path, "w") as f:
        f.write("// %d-to-%d decoder%s (behavioural reference)\n" % (n, N, " with enable" if en else ""))
        f.write("module %s_rtl (%s);\n" % (blk.name, "A, EN, Y" if en else "A, Y"))
        f.write(_port_decl(blk.ports) + "\n")
        if en:
            f.write("  assign Y = EN ? ({{%d{1'b0}}, 1'b1} << A) : {%d{1'b0}};\n" % (N - 1, N))
        else:
            f.write("  assign Y = {{%d{1'b0}}, 1'b1} << A;\n" % (N - 1))
        f.write("endmodule\n")


def write_decoder_tb(blk, path):
    """Exhaustive testbench: for every A (and EN) exactly the expected outputs are high."""
    n, en = blk.meta["n_bits"], blk.meta["enable"]
    N = 1 << n
    with open(path, "w") as f:
        f.write("`timescale 1ns/1ps\nmodule tb_%s;\n" % blk.name)
        f.write("  reg [%d:0] A;\n  reg EN;\n  wire [%d:0] Y;\n  integer i, e, errors;\n" % (n - 1, N - 1))
        f.write("  %s dut (.A(A), %s.Y(Y));\n" % (blk.name, ".EN(EN), " if en else ""))
        f.write("  initial begin\n    errors = 0;\n")
        f.write("    for (e = %d; e < 2; e = e + 1)\n" % (0 if en else 1))
        f.write("      for (i = 0; i < %d; i = i + 1) begin\n" % N)
        f.write("        A = i; EN = e; #10;\n")
        f.write("        if (Y !== (e ? ({{%d{1'b0}}, 1'b1} << i) : {%d{1'b0}})) begin\n" % (N - 1, N))
        f.write("          errors = errors + 1;\n")
        f.write("          if (errors <= 10) $display(\"FAIL EN=%0d A=%0d\", e, i);\n")
        f.write("        end\n      end\n")
        f.write("    if (errors == 0) $display(\"PASS: %s exhaustive\");\n" % blk.name)
        f.write("    else $display(\"FAILED: %0d vectors wrong\", errors);\n")
        f.write("    $finish;\n  end\nendmodule\n")


def write_all(blk, outdir, spice=None):
    """Write the block files. ``spice``: a :class:`dla.spice_artifacts.SpiceOptions` to also write the
    structural ``<name>.spice`` (when the tech file configures ``spice.cell_library``), the
    ``<name>.spice.json`` metadata and the schematic SVG; the report is left on ``blk.spice``."""
    os.makedirs(outdir, exist_ok=True)
    paths = {"json": os.path.join(outdir, blk.name + ".json"),
             "netlist": os.path.join(outdir, blk.name + "_layout.v")}
    with open(paths["json"], "w") as f:
        json.dump(block_json(blk), f)
    write_verilog(blk, paths["netlist"])
    if blk.meta.get("block") == "decoder":
        paths["rtl"] = os.path.join(outdir, blk.name + "_rtl.v")
        paths["tb"] = os.path.join(outdir, blk.name + "_tb.v")
        write_decoder_rtl(blk, paths["rtl"])
        write_decoder_tb(blk, paths["tb"])
    if spice is not None:
        from . import spice_artifacts
        blk.spice = spice_artifacts.finalize_block(blk, outdir, paths, spice)
        paths.update(blk.spice["paths"])
    return paths
